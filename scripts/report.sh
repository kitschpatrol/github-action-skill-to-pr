#!/usr/bin/env bash
set -euo pipefail

cd "$GITHUB_WORKSPACE"

if [[ "${STP_CONCLUSION:-}" != 'success' ]]; then
	echo '::error::Claude did not complete successfully. Refusing to publish partial changes.' >&2
	exit 1
fi

if [[ "$(git rev-parse HEAD)" != "$(cat "$STP_DIRECTORY/head")" ||
"$(git symbolic-ref --quiet --short HEAD)" != "$(cat "$STP_DIRECTORY/base")" ]]; then
	echo '::error::Claude changed HEAD or switched branches. Refusing to publish; inspect the workflow run.' >&2
	exit 1
fi

report="$STP_DIRECTORY/report.md"
body="$STP_DIRECTORY/body.md"
# Claude writes the report last, so a missing one means the session ended early.
if [[ ! -s "$report" ]]; then
	echo '::error::Claude ended without writing its report, so the skill probably did not finish. Refusing to publish partial changes.' >&2
	if [[ -s "${STP_EXECUTION_FILE:-}" ]]; then
		echo "::group::Claude's final message and last tool calls"
		# Tool outputs stay out of the log because that's where secrets usually surface.
		node --input-type=module - "$STP_EXECUTION_FILE" << 'JS'
import { readFileSync } from 'node:fs'
const messages = JSON.parse(readFileSync(process.argv[2], 'utf8'))
const result = messages.findLast((message) => message.type === 'result')
const toolCalls = messages
  .filter((message) => message.type === 'assistant' && !message.parent_tool_use_id)
  .flatMap((message) => message.message.content)
  .filter((block) => block.type === 'tool_use')
  .slice(-10)
console.log(`Final message:\n${result?.result ?? '(none)'}\n\nLast tool calls:`)
for (const call of toolCalls) {
  console.log(`${call.name} ${JSON.stringify(call.input).slice(0, 200)}`)
}
JS
		echo '::endgroup::'
	fi
	exit 1
fi
cat "$report" >> "$GITHUB_STEP_SUMMARY"

# Leave room for the footer within GitHub's 65,536-character PR body limit.
# Decode after slicing to avoid emitting a partial UTF-8 character.
node --input-type=module - "$report" "$body" << 'JS'
import { readFileSync, writeFileSync } from 'node:fs'
const [report, body] = process.argv.slice(2)
const content = readFileSync(report)
let text = new TextDecoder().decode(content.subarray(0, 60000), { stream: true })
if (content.length > 60000) {
  text += '\n\n_Report truncated. The full report is in the workflow run summary._\n'
}
writeFileSync(body, text)
JS
printf '\n\n---\n\nGenerated by the `%s` skill in [this workflow run](%s).\n' "$STP_SKILL" "$STP_RUN_URL" >> "$body"
